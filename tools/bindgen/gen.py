#!/usr/bin/env python3
"""Generate the Odin `sce` bindings from the installed VitaSDK headers.

    python tools/bindgen/gen.py            (from the repo root)

What it does:
  1. Preprocesses every user-mode header (psp2/**, psp2common/**) with
     arm-vita-eabi-gcc and parses the result with pycparser.
  2. Asks GCC (not this script) for every struct size, field offset, enum size,
     enum value and macro value, by compiling a probe file to assembly.
  3. Looks up which stub library exports each function (arm-vita-eabi-nm).
  4. Writes one Odin file per header into lib/sce/, a C float bridge
     (lib/sce/bridge.c), and a report (tools/bindgen/report.md).

Hand-written files in lib/sce/ are never touched: only files that start with
the GENERATED marker are replaced.

Requires: Python 3, pycparser (`pip install pycparser`), VitaSDK.
"""
import glob
import os
import re
import subprocess
import sys

from pycparser import CParser, c_ast

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
WORK = os.path.join(HERE, "work")
OUT = os.path.join(ROOT, "lib", "sce")
VITASDK = os.environ.get("VITASDK", r"C:\vitasdk")
INC = os.path.join(VITASDK, "arm-vita-eabi", "include")
LIBDIR = os.path.join(VITASDK, "arm-vita-eabi", "lib")
GCC = os.path.join(VITASDK, "bin", "arm-vita-eabi-gcc")
NM = os.path.join(VITASDK, "bin", "arm-vita-eabi-nm")
MARK = "// GENERATED by tools/bindgen/gen.py"

ARCH = ["-march=armv7-a", "-mtune=cortex-a9", "-mfpu=neon", "-mfloat-abi=hard"]

# Headers left out, with the reason (shown in the report).
SKIP_HEADERS = {
    "psp2/paf.h": "umbrella include only",
    "psp2/paf/stdc.h": "ScePaf copies of libc (sce_paf_private_*); system-app only",
    "psp2/paf/misc.h": "ScePaf, system-app only",
    "psp2/paf/graphics.h": "ScePaf, system-app only",
}

# Stub libraries are tried in this order when several export the same name.
LIB_PREFERENCE = ["SceLibKernel", "SceKernelThreadMgr", "SceIofilemgr", "SceSysmem", "SceProcessmgr"]

ODIN_KEYWORDS = set("""align_of auto_cast bit_field bit_set break case cast context continue defer
distinct do dynamic else enum fallthrough for foreign if import in map matrix not_in or_else
or_return or_break or_continue package proc return size_of offset_of type_of struct switch
transmute typeid union using when where asm inline no_inline nil true false string cstring rawptr
any bool int uint""".split())

PRIMS = {
    "char": "u8", "signed char": "i8", "unsigned char": "u8",
    "short": "i16", "unsigned short": "u16", "int": "i32", "unsigned int": "u32",
    "long": "i32", "unsigned long": "u32", "long long": "i64", "unsigned long long": "u64",
    "float": "f32", "double": "f64", "long double": "f64", "_Bool": "bool", "void": "void",
}
PRIM_SIZE = {"u8": 1, "i8": 1, "u16": 2, "i16": 2, "u32": 4, "i32": 4, "u64": 8, "i64": 8,
             "f32": 4, "f64": 8, "bool": 1, "rawptr": 4, "cstring": 4}

# SDK typedefs that are just spelled-out primitives: written as the primitive.
PRIM_TYPEDEF = re.compile(r"^Sce(U?Int(8|16|32|64)?|U?Char8|WChar(16|32)|U?Short16|U?Long64|Float(32)?"
                          r"|Double(64)?|Void|S?Byte8?|PVoid)$")

report = {"skipped_headers": [], "no_stub": [], "inline": [], "macros_skipped": [], "bridged": [],
          "float_struct": [], "notes": [], "func_macros": []}


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.stderr.write(r.stderr[-6000:])
        raise SystemExit("command failed: " + " ".join(cmd[:4]))
    return r.stdout


def norm(p):
    return os.path.normpath(p).replace("\\", "/")


INCN = norm(INC)


def rel_header(path):
    p = norm(path)
    if p.lower().startswith(INCN.lower() + "/"):
        return p[len(INCN) + 1:]
    return None


def is_sdk(relp):
    return relp is not None and (relp.startswith("psp2/") or relp.startswith("psp2common/"))


def out_key(relp):
    """psp2/kernel/threadmgr/mutex.h and psp2common/... -> kernel_threadmgr_mutex"""
    p = relp.split("/", 1)[1]
    return p[:-2].replace("/", "_")


# ---------------------------------------------------------------- naming
def strip_type(n):
    if n.startswith("Sce") and len(n) > 3 and (n[3].isupper() or n[3].isdigit()):
        n = n[3:]
    if n[0].isdigit():
        n = "_" + n
    return n


def strip_const(n):
    if n.startswith("SCE_") and len(n) > 4:
        n = n[4:]
    if n[0].isdigit():
        n = "_" + n
    return n


def ident(n):
    if n in ODIN_KEYWORDS:
        return n + "_"
    return n


# ---------------------------------------------------------------- inputs
def collect_headers():
    hs = []
    for root in ("psp2common", "psp2"):
        for p in glob.glob(os.path.join(INC, root, "**", "*.h"), recursive=True):
            r = rel_header(p)
            if r in SKIP_HEADERS:
                report["skipped_headers"].append((r, SKIP_HEADERS[r]))
                continue
            hs.append(r)
    hs.sort(key=lambda r: (0 if r.startswith("psp2common/") else 1, r))
    return hs


def preprocess(headers):
    os.makedirs(WORK, exist_ok=True)
    src = "".join(f"#include <{h}>\n" for h in headers)
    allc = os.path.join(WORK, "all.c")
    open(allc, "w").write(src)
    defs = ["-D__attribute__(x)=", "-D__extension__=", "-D__inline=inline", "-D__inline__=inline",
            "-D__restrict=", "-D__restrict__=", "-D__asm__(x)=", "-D__builtin_va_list=int",
            "-D_Noreturn=", "-D__GNUC_VA_LIST", "-D__gnuc_va_list=int"]
    run([GCC, "-E", "-std=gnu11", *defs, allc, "-o", os.path.join(WORK, "all.i")])
    run([GCC, "-E", "-dD", "-std=gnu11", allc, "-o", os.path.join(WORK, "all.dD")])
    return open(os.path.join(WORK, "all.i")).read(), open(os.path.join(WORK, "all.dD")).read()


def stub_map():
    """function name -> stub library name (without lib / .a)"""
    cache = os.path.join(WORK, "stubs.txt")
    if not os.path.exists(cache):
        lines = []
        for a in sorted(glob.glob(os.path.join(LIBDIR, "lib*_stub.a"))):
            lib = os.path.basename(a)[3:-2]
            if "ForDriver" in lib or "ForKernel" in lib:
                continue
            out = subprocess.run([NM, a], capture_output=True, text=True).stdout
            for ln in out.splitlines():
                m = re.match(r"^[0-9a-f]+ T (\w+)$", ln)
                if m:
                    lines.append(f"{m.group(1)} {lib}")
        open(cache, "w").write("\n".join(lines))
    m = {}
    for ln in open(cache).read().splitlines():
        fn, lib = ln.split()
        m.setdefault(fn, []).append(lib)

    def pick(libs):
        for pref in LIB_PREFERENCE:
            if pref + "_stub" in libs:
                return pref + "_stub"
        return sorted(libs, key=lambda l: (len(l), l))[0]
    return {fn: pick(libs) for fn, libs in m.items()}


# ---------------------------------------------------------------- header text (comments)
_hdr_lines = {}


def hdr_lines(relp):
    if relp not in _hdr_lines:
        try:
            _hdr_lines[relp] = open(os.path.join(INC, relp), encoding="utf-8", errors="replace").read().splitlines()
        except OSError:
            _hdr_lines[relp] = []
    return _hdr_lines[relp]


def clean_comment_lines(raw):
    out = []
    for ln in raw:
        ln = ln.strip()
        ln = re.sub(r"^/\*+!?<?", "", ln)
        ln = re.sub(r"\*+/$", "", ln)
        ln = re.sub(r"^\*+ ?", "", ln)
        ln = re.sub(r"^//+!?<? ?", "", ln)
        ln = re.sub(r"\s+", " ", ln.replace("	", " ")).strip()
        out.append(ln)
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return out


def doc_before(relp, line):
    """Comment block that ends right above `line` (1-based)."""
    L = hdr_lines(relp)
    i = line - 2
    if i < 0 or i >= len(L):
        return []
    s = L[i].strip()
    if s.endswith("*/"):
        j = i
        while j >= 0 and "/*" not in L[j]:
            j -= 1
        if j < 0:
            return []
        if L[j].strip().startswith("/*") and i - j < 60:
            block = clean_comment_lines(L[j:i + 1])
            if any("usergroup" in b or "\\usage" in b for b in block):
                return []
            return block
        return []
    if s.startswith("//"):
        j = i
        while j >= 0 and L[j].strip().startswith("//"):
            j -= 1
        return clean_comment_lines(L[j + 1:i + 1])
    return []


def trailing_comment(relp, line):
    L = hdr_lines(relp)
    if line - 1 < 0 or line - 1 >= len(L):
        return ""
    s = L[line - 1]
    m = re.search(r"//[!/]*<?\s*(.*)$", s)
    if m and "://" not in s[:m.start() + 2]:
        return m.group(1).strip()
    m = re.search(r"/\*+!*<?\s*(.*?)\s*\*/\s*$", s)
    if m:
        return m.group(1).strip()
    return ""


# ---------------------------------------------------------------- model
class Model:
    def __init__(self):
        self.typedefs = {}      # name -> (type node, relp, line)
        self.tags = {}          # ("struct"|"union"|"enum", tag) -> node with decls/values
        self.tag_alias = {}     # (kind, tag) -> emitted Odin name
        self.enum_consts = {}   # C name -> int
        self.enum_of_const = {}
        self.items = []         # (relp, line, kind, payload)
        self.funcs = {}         # name -> (decl, relp, line)
        self.inline_funcs = []


M = Model()


def coord_of(node):
    c = node.coord
    return rel_header(c.file), c.line


def base_names(t):
    """IdentifierType names joined and canonicalised."""
    names = [n for n in t.names if n not in ("const", "volatile")]
    s = " ".join(names)
    s = s.replace("signed char", "@sc")
    toks = [x for x in s.split() if x not in ("signed",)] if "@sc" not in s else s.split()
    s = " ".join(toks).replace("@sc", "signed char")
    canon = {
        "unsigned": "unsigned int", "": "int", "short int": "short", "unsigned short int": "unsigned short",
        "short unsigned int": "unsigned short", "long int": "long", "unsigned long int": "unsigned long",
        "long unsigned int": "unsigned long", "long long int": "long long",
        "unsigned long long int": "unsigned long long", "long long unsigned int": "unsigned long long",
        "char unsigned": "unsigned char", "int unsigned": "unsigned int", "int long": "long",
        "int short": "short", "long unsigned": "unsigned long", "short unsigned": "unsigned short",
        "long long unsigned": "unsigned long long",
    }
    return canon.get(s, s)


def resolve(t):
    """Follow typedefs to the underlying node (TypeDecl/PtrDecl/ArrayDecl/FuncDecl/Struct/Enum/IdentifierType)."""
    seen = 0
    while True:
        seen += 1
        if seen > 50:
            return t
        if isinstance(t, c_ast.TypeDecl):
            t = t.type
            continue
        if isinstance(t, c_ast.IdentifierType):
            n = base_names(t)
            if n in M.typedefs:
                t = M.typedefs[n][0]
                continue
        return t


def tag_def(node):
    """Struct/Union/Enum node -> the node that has the body (or None)."""
    kind = {c_ast.Struct: "struct", c_ast.Union: "union", c_ast.Enum: "enum"}[type(node)]
    body = node.decls if kind != "enum" else node.values
    if body is not None:
        return node
    if node.name and (kind, node.name) in M.tags:
        return M.tags[(kind, node.name)]
    return None


def is_float_by_value(t):
    r = resolve(t)
    return isinstance(r, c_ast.IdentifierType) and base_names(r) in ("float", "double", "long double")


def struct_has_float(t, depth=0):
    r = resolve(t)
    if isinstance(r, (c_ast.Struct, c_ast.Union)):
        d = tag_def(r)
        if d is None or depth > 6:
            return False
        for f in d.decls or []:
            ft = f.type
            while isinstance(ft, c_ast.ArrayDecl):
                ft = ft.type
            if is_float_by_value(ft) or struct_has_float(ft, depth + 1):
                return True
    return False


# ---------------------------------------------------------------- constant expressions
def ceval(n):
    if isinstance(n, c_ast.Constant):
        if n.type in ("char",):
            s = n.value[1:-1]
            if s.startswith("\\"):
                esc = {"n": 10, "t": 9, "0": 0, "r": 13, "\\": 92, "'": 39}
                return esc.get(s[1], ord(s[1]))
            return ord(s)
        v = n.value.rstrip("uUlL")
        return int(v, 0) if not (len(v) > 1 and v[0] == "0" and v[1].isdigit()) else int(v, 8)
    if isinstance(n, c_ast.ID):
        if n.name in M.enum_consts:
            return M.enum_consts[n.name]
        raise ValueError("unknown id " + n.name)
    if isinstance(n, c_ast.UnaryOp):
        if n.op == "sizeof":
            return csizeof(n.expr)
        v = ceval(n.expr)
        return {"-": -v, "+": v, "~": ~v, "!": int(not v)}[n.op]
    if isinstance(n, c_ast.BinaryOp):
        a, b = ceval(n.left), ceval(n.right)
        ops = {"+": lambda: a + b, "-": lambda: a - b, "*": lambda: a * b, "/": lambda: int(a / b),
               "%": lambda: a % b, "<<": lambda: a << b, ">>": lambda: a >> b, "|": lambda: a | b,
               "&": lambda: a & b, "^": lambda: a ^ b, "==": lambda: int(a == b), "!=": lambda: int(a != b),
               "<": lambda: int(a < b), ">": lambda: int(a > b), "<=": lambda: int(a <= b),
               ">=": lambda: int(a >= b), "&&": lambda: int(bool(a) and bool(b)),
               "||": lambda: int(bool(a) or bool(b))}
        return ops[n.op]()
    if isinstance(n, c_ast.Cast):
        return ceval(n.expr)
    if isinstance(n, c_ast.TernaryOp):
        return ceval(n.iftrue) if ceval(n.cond) else ceval(n.iffalse)
    raise ValueError("cannot evaluate " + type(n).__name__)


def csizeof(n):
    t = n.type if isinstance(n, c_ast.Typename) else n
    r = resolve(t)
    if isinstance(r, c_ast.PtrDecl):
        return 4
    if isinstance(r, c_ast.IdentifierType):
        return PRIM_SIZE[PRIMS[base_names(r)]]
    if isinstance(r, c_ast.ArrayDecl):
        return ceval(r.dim) * csizeof(r.type)
    name = None
    if isinstance(t, c_ast.TypeDecl) and isinstance(t.type, c_ast.IdentifierType):
        name = base_names(t.type)
    if name and name in GCCV.sizes:
        return GCCV.sizes[name]
    raise ValueError("sizeof")


# ---------------------------------------------------------------- GCC probe (ground truth)
class GccValues:
    def __init__(self):
        self.sizes = {}     # C type name -> size
        self.offsets = {}   # (C type name, field) -> offset
        self.consts = {}    # C constant name -> int (as written in C, non-negative unless negative)


GCCV = GccValues()


def gcc_probe(headers, type_names, field_list, const_names, tagname="probe"):
    """Compile a probe and read back the numbers. const_names must be valid integer expressions."""
    src = ["".join(f"#include <{h}>\n" for h in headers)]
    for i, t in enumerate(type_names):
        src.append(f"const unsigned vito_sz_{i} = sizeof({t});\n")
    for i, (t, f) in enumerate(field_list):
        src.append(f"const unsigned vito_of_{i} = __builtin_offsetof({t}, {f});\n")
    for i, c in enumerate(const_names):
        src.append(f"const long long vito_cv_{i} = (long long)({c});\n")
        src.append(f"const int vito_cn_{i} = (({c}) < 0);\n")
    cfile = os.path.join(WORK, tagname + ".c")
    sfile = os.path.join(WORK, tagname + ".s")
    open(cfile, "w").write("".join(src))
    r = subprocess.run([GCC, "-S", "-O0", "-w", *ARCH, cfile, "-o", sfile], capture_output=True, text=True)
    if r.returncode != 0:
        return r.stderr
    vals = {}
    cur = None
    for ln in open(sfile).read().splitlines():
        m = re.match(r"^(vito_\w+):", ln)
        if m:
            cur = m.group(1)
            vals[cur] = []
            continue
        m = re.match(r"^\s+\.(word|long|space)\s+(-?\d+)", ln)
        if m and cur:
            if m.group(1) == "space":
                vals[cur] += [0] * (int(m.group(2)) // 4)
            else:
                vals[cur].append(int(m.group(2)) & 0xFFFFFFFF)
        elif cur and not re.match(r"^\s+\.(size|type|align|global|section)", ln):
            cur = None if not ln.startswith("\t.") else cur
    for i, t in enumerate(type_names):
        GCCV.sizes[t] = vals[f"vito_sz_{i}"][0]
    for i, tf in enumerate(field_list):
        GCCV.offsets[tf] = vals[f"vito_of_{i}"][0]
    for i, c in enumerate(const_names):
        w = vals[f"vito_cv_{i}"]
        v = w[0] | (w[1] << 32)
        neg = vals[f"vito_cn_{i}"][0]
        if neg:
            v -= 1 << 64
        GCCV.consts[c] = v
    return None


def gcc_probe_robust(headers, const_names, tagname):
    """Like gcc_probe for constants only, dropping the ones GCC rejects."""
    names = list(const_names)
    for _ in range(12):
        err = gcc_probe(headers, [], [], names, tagname)
        if err is None:
            return names
        bad = set()
        for m in re.finditer(r"%s\.c:(\d+):" % re.escape(tagname), err):
            bad.add(int(m.group(1)))
        if not bad:
            sys.stderr.write(err[-3000:])
            raise SystemExit("macro probe failed")
        base = len(headers) + 1
        drop = set((ln - base) // 2 for ln in bad if ln >= base)
        for i in drop:
            if 0 <= i < len(names):
                report["macros_skipped"].append((names[i], "not an integer constant expression"))
        names = [n for i, n in enumerate(names) if i not in drop]
    raise SystemExit("macro probe did not converge")


# ---------------------------------------------------------------- AST collection
def collect(ast):
    for ext in ast.ext:
        relp, line = coord_of(ext)
        sdk = is_sdk(relp)
        if isinstance(ext, c_ast.Typedef):
            M.typedefs[ext.name] = (ext.type, relp, line)
            register_tags(ext.type, relp, sdk, typedef_name=ext.name)
            if sdk:
                M.items.append((relp, line, "typedef", ext))
        elif isinstance(ext, c_ast.Decl):
            if isinstance(ext.type, c_ast.FuncDecl):
                if sdk and ext.name not in M.funcs:
                    M.funcs[ext.name] = (ext, relp, line)
                    M.items.append((relp, line, "func", ext))
            elif isinstance(ext.type, (c_ast.Struct, c_ast.Union, c_ast.Enum)):
                register_tags(ext.type, relp, sdk, typedef_name=None, standalone=True)
            # extern variables are ignored
        elif isinstance(ext, c_ast.FuncDef):
            if sdk:
                M.inline_funcs.append((ext.decl.name, relp, line))
        # StaticAssert etc: ignored


def register_tags(t, relp, sdk, typedef_name=None, standalone=False):
    """Record struct/union/enum definitions found directly in a declaration."""
    inner = t
    while isinstance(inner, (c_ast.TypeDecl,)):
        inner = inner.type
    if isinstance(inner, (c_ast.Struct, c_ast.Union)):
        kind = "struct" if isinstance(inner, c_ast.Struct) else "union"
        if inner.decls is not None and inner.name:
            M.tags[(kind, inner.name)] = inner
            if standalone and sdk:
                M.items.append((relp, inner.coord.line, "tagdef", inner))
    elif isinstance(inner, c_ast.Enum):
        if inner.values is not None:
            if inner.name:
                M.tags[("enum", inner.name)] = inner
            nxt = 0
            for e in inner.values.enumerators:
                if e.value is not None:
                    nxt = ceval(e.value)
                M.enum_consts[e.name] = nxt
                M.enum_of_const[e.name] = inner
                nxt += 1
            if standalone and sdk:
                M.items.append((relp, inner.coord.line, "tagdef", inner))


# ---------------------------------------------------------------- Odin type printing
class Ctx:
    def __init__(self):
        self.used_types = set()


def odin_named(name):
    """C typedef/primitive name -> Odin spelling."""
    if name in PRIMS:
        return PRIMS[name]
    if name in ("va_list", "__gnuc_va_list", "__builtin_va_list"):
        return "rawptr"
    if PRIM_TYPEDEF.match(name):
        r = resolve(M.typedefs[name][0])
        if isinstance(r, c_ast.PtrDecl):
            return "rawptr"
        return PRIMS[base_names(r)]
    if name in M.typedefs:
        _, relp, _ = M.typedefs[name]
        if is_sdk(relp):
            return strip_type(name)
        # libc typedef (uint32_t, size_t, ...): spell the underlying type
        return otype(M.typedefs[name][0])
    raise ValueError("unknown type name: " + name)


def pointee_is(t, what):
    r = t
    if isinstance(r, c_ast.TypeDecl):
        r = r.type
    return isinstance(r, c_ast.IdentifierType) and base_names(r) in what


def is_const(t):
    return isinstance(t, c_ast.TypeDecl) and "const" in (t.quals or [])


def func_typedef_name(t):
    """If t is a typedef name whose target is a function type (not pointer), return the name."""
    if isinstance(t, c_ast.TypeDecl) and isinstance(t.type, c_ast.IdentifierType):
        n = base_names(t.type)
        if n in M.typedefs and isinstance(M.typedefs[n][0], c_ast.FuncDecl):
            return n
    return None


def otype(t, in_param=False):
    if isinstance(t, c_ast.TypeDecl):
        return otype(t.type, in_param)
    if isinstance(t, c_ast.IdentifierType):
        n = base_names(t)
        o = odin_named(n)
        return o
    if isinstance(t, c_ast.PtrDecl):
        inner = t.type
        if isinstance(inner, c_ast.FuncDecl):
            return proc_type(inner)
        fn = func_typedef_name(inner)
        if fn:
            return odin_named(fn)
        if pointee_is(inner, ("void", "SceVoid")):
            return "rawptr"
        if pointee_is(inner, ("char", "SceChar8")):
            return "cstring" if is_const(inner) else "[^]u8"
        if pointee_is(inner, ("unsigned char", "signed char", "SceUChar8", "SceUInt8", "SceByte", "SceByte8",
                              "uint8_t", "SceWChar16", "SceWChar32", "wchar_t")):
            return "[^]" + otype(inner)
        it = otype(inner)
        if it == "void":
            return "rawptr"
        return "^" + it
    if isinstance(t, c_ast.ArrayDecl):
        if in_param:
            return "[^]" + otype(t.type)
        dim = 0 if t.dim is None else ceval(t.dim)
        return f"[{dim}]{otype(t.type)}"
    if isinstance(t, c_ast.FuncDecl):
        return proc_type(t)
    if isinstance(t, (c_ast.Struct, c_ast.Union)):
        kind = "struct" if isinstance(t, c_ast.Struct) else "union"
        if t.name and (kind, t.name) in M.tag_alias:
            return M.tag_alias[(kind, t.name)]
        if t.decls is not None:
            return struct_body(t, None, indent=1)
        if t.name:
            # forward reference to a tag that is never defined or defined later
            if (kind, t.name) in M.tags:
                return strip_type(t.name)
            M.tag_alias[(kind, t.name)] = strip_type(t.name)
            PENDING_OPAQUE.add(strip_type(t.name))
            return strip_type(t.name)
        raise ValueError("anonymous incomplete struct")
    if isinstance(t, c_ast.Enum):
        if t.name and ("enum", t.name) in M.tag_alias:
            return M.tag_alias[("enum", t.name)]
        return "i32"
    raise ValueError("otype: " + type(t).__name__)


PENDING_OPAQUE = set()


def params_of(fd):
    """[(name, type node)] with (void) -> [], and the variadic flag."""
    out = []
    variadic = False
    if fd.args is None:
        return out, variadic
    for i, p in enumerate(fd.args.params):
        if isinstance(p, c_ast.EllipsisParam):
            variadic = True
            continue
        if isinstance(p, c_ast.Typename):
            pt, pn = p.type, None
        else:
            pt, pn = p.type, p.name
        r = pt
        if isinstance(r, c_ast.TypeDecl) and isinstance(r.type, c_ast.IdentifierType) and base_names(r.type) == "void":
            continue
        out.append((pn or f"arg{i}", pt))
    return out, variadic


def is_void(t):
    r = resolve(t)
    return isinstance(r, c_ast.IdentifierType) and base_names(r) == "void"


def proc_sig(fd, noreturn=False):
    ps, variadic = params_of(fd)
    parts = [f"{ident(n)}: {otype(t, in_param=True)}" for n, t in ps]
    if variadic:
        parts.append("#c_vararg args: ..any")
    s = "proc(" + ", ".join(parts) + ")"
    if noreturn:
        s += " -> !"
    elif not is_void(fd.type):
        s += " -> " + otype(fd.type)
    return s


def proc_type(fd):
    return proc_sig(fd).replace("proc(", 'proc "c" (', 1)


# struct emission ------------------------------------------------------------
STRUCT_ATTR = {"SceFiber": "#align(8)", "SceFiberOptParam": "#align(8)", "SceFiberInfo": "#align(8)",
               "SceUsbdDeviceAddress": "#packed"}


def field_c_size(ft):
    """Size GCC gives a scalar field type, when we can know it (enums are short)."""
    r = resolve(ft)
    if isinstance(r, c_ast.Enum):
        tn = None
        if isinstance(ft, c_ast.TypeDecl) and isinstance(ft.type, c_ast.IdentifierType):
            tn = base_names(ft.type)
        if tn is None and r.name:
            tn = "enum " + r.name
        return GCCV.sizes.get(tn)
    return None


def field_type(ft, relp=None):
    """Odin type for a struct field. Enum-typed fields take GCC's (short) enum size."""
    arr = []
    t = ft
    while isinstance(t, c_ast.ArrayDecl):
        arr.append(0 if t.dim is None else ceval(t.dim))
        t = t.type
    r = resolve(t)
    if isinstance(r, c_ast.Enum):
        sz = field_c_size(t)
        if sz is not None and sz != 4:
            d = tag_def(r)
            neg = d is not None and any(M.enum_consts[e.name] < 0 for e in d.values.enumerators)
            base = {1: "u8", 2: "u16", 8: "u64"}[sz]
            if neg:
                base = "i" + base[1:]
            return "".join(f"[{d}]" for d in arr) + base, otype(t)
    return otype(ft), None


def struct_body(node, cname, indent=0, relp=None):
    kind = "struct"
    tags = []
    if isinstance(node, c_ast.Union):
        tags.append("#raw_union")
    if cname in STRUCT_ATTR:
        tags.append(STRUCT_ATTR[cname])
    pad = "    " * (indent + 1)
    lines = []
    fields = []   # (name, type, comment)
    bf = None     # pending bitfield group: [base, bits_used, [(name, width)]]
    bfn = [0]

    def flush():
        nonlocal bf
        if bf:
            base, used, members = bf
            inner = ", ".join(f"{ident(n)}: {base} | {w}" for n, w in members)
            fields.append((f"using _bf{bfn[0]}", f"bit_field {base} {{{inner}}}", ""))
            bfn[0] += 1
            bf = None

    anon = 0
    for f in node.decls or []:
        if not isinstance(f, c_ast.Decl):
            continue
        cmt = trailing_comment(relp, f.coord.line) if relp and f.coord else ""
        if f.bitsize is not None:
            base = otype(f.type)
            w = ceval(f.bitsize)
            bits = PRIM_SIZE.get(base, 4) * 8
            if bf and (bf[0] != base or bf[1] + w > bits or w == 0):
                flush()
            if w == 0:
                continue
            if not bf:
                bf = [base, 0, []]
            name = f.name or f"_pad{len(bf[2])}_{bfn[0]}"
            bf[2].append((name, w))
            bf[1] += w
            continue
        flush()
        if f.name is None:
            # anonymous struct/union member
            ft = f.type
            body = otype(ft)
            fields.append((f"using _anon{anon}", body, cmt))
            anon += 1
            continue
        ty, enum_note = field_type(f.type, relp)
        if enum_note:
            cmt = (enum_note + (": " + cmt if cmt else ""))
        fields.append((ident(f.name), ty, cmt))
    flush()
    head = "struct " + " ".join(tags) + (" " if tags else "") + "{"
    if not fields:
        return head + "}"
    w = max(len(n) for n, _, _ in fields) + 1
    lines.append(head)
    for n, ty, cmt in fields:
        ty_i = ty.replace("\n", "\n" + "    ")
        s = f"{pad}{(n + ':').ljust(w)} {ty_i},"
        if cmt:
            s += " // " + cmt
        lines.append(s)
    lines.append("    " * indent + "}")
    return "\n".join(lines)


# ---------------------------------------------------------------- enums
def common_prefix(names):
    names = [n for n in names if not n.startswith("__")] or names
    if len(names) < 2:
        return ""
    parts = [n.split("_") for n in names]
    k = 0
    while all(len(p) > k + 1 for p in parts) and len(set(p[k] for p in parts)) == 1:
        k += 1
    return "_".join(parts[0][:k]) + ("_" if k else "")


def enum_mode(cname, node):
    """'enum' -> Odin enum; 'const' -> untyped constants plus an integer alias."""
    es = node.values.enumerators
    vals = [M.enum_consts[e.name] for e in es]
    if cname is None:
        return "const"
    if len(es) < 2:
        return "const"
    if cname not in USED_TYPE_NAMES and not (node.name and ("enum " + node.name) in USED_TYPE_NAMES):
        return "const"   # no function or struct takes this type, so an Odin enum would always need a cast
    if re.search(r"(Error|ErrorCode|Errors|Flag|Flags|Mask|Attr|Attribute|Attributes|Buttons)$", cname):
        return "const"
    if any(v >= 0x80000000 for v in vals) and any(v > 0x80000000 and v < 0x90000000 for v in vals) \
            and sum(1 for v in vals if 0x80000000 <= v < 0x90000000) >= len(vals) // 2:
        return "const"   # error-code tables
    distinct = sorted(set(v for v in vals if v != 0))
    single = [v for v in distinct if v > 0 and v & (v - 1) == 0]
    if len(distinct) >= 3 and max(distinct) >= 8 and len(single) * 4 >= len(distinct) * 3:
        return "const"   # bit flags
    return "enum"


USED_TYPE_NAMES = set()


class _UseVisitor(c_ast.NodeVisitor):
    def visit_IdentifierType(self, n):
        USED_TYPE_NAMES.add(" ".join(n.names))

    def visit_Enum(self, n):
        if n.name and n.values is None:
            USED_TYPE_NAMES.add("enum " + n.name)
        self.generic_visit(n)


def enum_backing(vals):
    return "i32" if any(v < 0 for v in vals) else "u32"


def is_error_table(cname, vals):
    n = sum(1 for v in vals if 0x80000000 <= v < 0x90000000)
    if n == 0:
        return False
    if cname and re.search(r"(Error|ErrorCode|Errors)$", cname):
        return True
    return n * 2 >= len(vals)


def errval(v):
    """SCE error codes come back as a negative int: write them so they compare with an i32."""
    return "0x%08X - 1<<32" % v


def enum_is_octal(es):
    return any(e.value is not None and isinstance(e.value, c_ast.Constant)
               and re.fullmatch(r"0[0-7]+", e.value.value) for e in es)


def hexish(v, like_hex):
    if like_hex == "octal" and v >= 0:
        return "0o%o" % v
    if like_hex and v >= 0:
        return "0x%08X" % v if v > 0xFFFF else "0x%X" % v
    return str(v)


# ---------------------------------------------------------------- macros
def parse_macros(dd):
    """-> ordered list of (name, value text, relp, line) for object-like macros in SDK headers."""
    out = []
    cur_file, cur_line = None, 0
    for ln in dd.splitlines():
        m = re.match(r'^# (\d+) "([^"]+)"', ln)
        if m:
            cur_line = int(m.group(1)) - 1
            cur_file = rel_header(m.group(2).replace("\\\\", "/"))
            continue
        cur_line += 1
        if not is_sdk(cur_file):
            continue
        m = re.match(r"^#define (\w+)(\(.*?\))?\s*(.*)$", ln)
        if not m:
            continue
        name, args, val = m.group(1), m.group(2), m.group(3).strip()
        if args is not None and ln[len("#define ") + len(name)] == "(":
            report["func_macros"].append((name, cur_file))
            continue
        if args is not None:
            val = (args + " " + val).strip()
        val = re.sub(r"/\*.*?\*/", "", val).strip()
        val = re.sub(r"//.*$", "", val).strip()
        if not val:
            continue
        out.append((name, val, cur_file, cur_line))
    return out


_NUM = re.compile(r"\b(0[xX][0-9a-fA-F]+|\d+)[uUlL]*\b")


def macro_candidate_kind(val, known_consts, known_types, known_funcs):
    v = val.strip()
    if re.fullmatch(r'"(?:[^"\\]|\\.)*"', v):
        return "string"
    if re.fullmatch(r"\(?\s*-?\d+\.\d*(?:[eE][-+]?\d+)?[fF]?\s*\)?", v) or re.fullmatch(r"\(?\s*-?\d+[fF]\s*\)?", v):
        return "float"
    if re.fullmatch(r"\w+", v):
        if v in known_types:
            return "typealias"
        if v in known_funcs:
            return "funcalias"
    # integer expression: only numbers, operators, parens, known identifiers / type names
    toks = re.findall(r"[A-Za-z_]\w*", _NUM.sub("0", v))
    for t in toks:
        if t in known_consts or t in known_types or t in ("sizeof", "unsigned", "signed", "int", "long", "short", "char"):
            continue
        return None
    if re.search(r'["{};=\[\]]', v.replace("==", "").replace("!=", "").replace("<=", "").replace(">=", "")):
        return None
    if "'" in v and not re.fullmatch(r"'.'", v):
        return None
    return "int"


# ---------------------------------------------------------------- emission
def comment_block(lines, indent=""):
    return "".join(f"{indent}//{(' ' + l) if l else ''}\n" for l in lines)


class FileOut:
    def __init__(self, key):
        self.key = key
        self.headers = []
        self.body = []      # (sortkey, text)
        self.funcs = {}     # lib -> [text]
        self.bridged = []   # text lines
        self.nfuncs = 0


def main():
    headers = collect_headers()
    pre, dd = preprocess(headers)
    ast = CParser().parse(pre, "all.i")
    stubs = stub_map()
    collect(ast)
    _UseVisitor().visit(ast)

    # ---- names of things GCC must measure
    type_names = []
    struct_fields = []
    for name, (t, relp, line) in M.typedefs.items():
        if not is_sdk(relp):
            continue
        r = resolve(t)
        if isinstance(r, (c_ast.Struct, c_ast.Union)):
            d = tag_def(r)
            if d is None:
                continue
            type_names.append(name)
            for f in d.decls or []:
                if isinstance(f, c_ast.Decl) and f.name and f.bitsize is None:
                    struct_fields.append((name, f.name))
        elif isinstance(r, c_ast.Enum):
            if tag_def(r) is not None:
                type_names.append(name)
    for (kind, tag), node in M.tags.items():
        if kind == "enum":
            type_names.append("enum " + tag)
    type_names = list(dict.fromkeys(type_names))
    err = gcc_probe(headers, type_names, struct_fields, [], "probe_types")
    if err:
        sys.stderr.write(err[-4000:])
        raise SystemExit("type probe failed")

    # ---- constants: enum members and integer macros, values from GCC
    macros = parse_macros(dd)
    known_types = set(M.typedefs) | set(PRIMS)
    known_funcs = set(M.funcs)
    known_consts = set(M.enum_consts)
    macro_kind = {}
    macro_def = {}
    changed = True
    for name, val, relp, line in macros:
        macro_def[name] = (val, relp, line)
    while changed:
        changed = False
        for name, (val, relp, line) in macro_def.items():
            if name in macro_kind:
                continue
            k = macro_candidate_kind(val, known_consts, known_types, known_funcs)
            if k:
                macro_kind[name] = k
                if k == "int":
                    known_consts.add(name)
                changed = True
    int_macros = [n for n, k in macro_kind.items() if k == "int"]
    ok = gcc_probe_robust(headers, list(M.enum_consts) + int_macros, "probe_consts")
    ok = set(ok)
    for n in list(M.enum_consts):
        if n in ok and GCCV.consts[n] != M.enum_consts[n]:
            report["notes"].append(f"enum constant {n}: script evaluated {M.enum_consts[n]}, GCC says {GCCV.consts[n]} (GCC used)")
            M.enum_consts[n] = GCCV.consts[n]
    for n in int_macros:
        if n not in ok:
            del macro_kind[n]

    # ---- decide Odin names for struct/union/enum tags via their typedefs
    for name, (t, relp, line) in M.typedefs.items():
        inner = t
        while isinstance(inner, c_ast.TypeDecl):
            inner = inner.type
        if isinstance(inner, (c_ast.Struct, c_ast.Union, c_ast.Enum)) and inner.name:
            kind = {c_ast.Struct: "struct", c_ast.Union: "union", c_ast.Enum: "enum"}[type(inner)]
            if is_sdk(relp):
                M.tag_alias.setdefault((kind, inner.name), strip_type(name))
    for (kind, tag), node in M.tags.items():
        relp = rel_header(node.coord.file)
        if is_sdk(relp):
            M.tag_alias.setdefault((kind, tag), strip_type(tag))

    files = {}

    def fo(relp):
        k = out_key(relp)
        if k not in files:
            files[k] = FileOut(k)
        if relp not in files[k].headers:
            files[k].headers.append(relp)
        return files[k]

    emitted_names = {}   # Odin top-level name -> description (collision check)
    enum_const_emitted = set()
    emitted_tags = set()
    bridge_c = []

    def claim(name, what):
        if name in emitted_names:
            return False
        emitted_names[name] = what
        return True

    def emit_enum(f, relp, line, cname, node, doc):
        if id(node) in emitted_tags:
            if cname and node.name and strip_type(cname) != M.tag_alias.get(("enum", node.name)):
                if claim(strip_type(cname), "alias"):
                    f.body.append(((relp, line), f"{strip_type(cname)} :: {M.tag_alias[('enum', node.name)]}\n"))
            return
        emitted_tags.add(id(node))
        es = node.values.enumerators
        vals = [M.enum_consts[e.name] for e in es]
        mode = enum_mode(cname, node)
        # Members named __SCE_... = 0xFFFFFFFF only force the C enum to 32 bits.
        # They are not values anyone passes, so they are left out.
        kept = [(e, v) for e, v in zip(es, vals) if not e.name.startswith("__")]
        if kept:
            es, vals = [e for e, _ in kept], [v for _, v in kept]
        like_hex = any(e.value is not None and (not isinstance(e.value, (c_ast.Constant, c_ast.UnaryOp))
                                                or (isinstance(e.value, c_ast.Constant)
                                                    and e.value.value.lower().startswith("0x"))) for e in es)
        if enum_is_octal(es):
            like_hex = "octal"
        txt = comment_block(doc)
        oname = strip_type(cname) if cname else None
        if mode == "enum" and oname and claim(oname, "enum"):
            prefix = common_prefix([e.name for e in es])
            members = []
            for e, v in zip(es, vals):
                mn = e.name[len(prefix):] if e.name.startswith(prefix) else e.name.lstrip("_")
                if not mn or mn[0].isdigit():
                    mn = "_" + mn
                members.append((ident(mn), v, trailing_comment(relp, e.coord.line)))
            w = max(len(m[0]) for m in members)
            txt += f"{oname} :: enum {enum_backing(vals)} {{\n"
            for mn, v, c in members:
                txt += f"    {mn.ljust(w)} = {hexish(v, like_hex)},"
                txt += f" // {c}\n" if c else "\n"
            txt += "}\n"
        else:
            errs = is_error_table(cname, vals)
            if oname:
                if claim(oname, "enum-alias"):
                    txt += f"{oname} :: {'i32' if errs else enum_backing(vals)}\n"
            names = [(strip_const(e.name), v, trailing_comment(relp, e.coord.line)) for e, v in zip(es, vals)]
            w = max(len(n[0]) for n in names)
            for n, v, c in names:
                if not claim(n, "const"):
                    continue
                enum_const_emitted.add(n)
                vtxt = errval(v) if errs and 0x80000000 <= v <= 0xFFFFFFFF else hexish(v, like_hex)
                txt += f"{n.ljust(w)} :: {vtxt}"
                txt += f" // {c}\n" if c else "\n"
        f.body.append(((relp, line), txt))

    def emit_struct(f, relp, line, cname, node, doc):
        oname = strip_type(cname)
        d = tag_def(node)
        if d is not None and id(d) in emitted_tags:
            kind = "struct" if isinstance(node, c_ast.Struct) else "union"
            target = M.tag_alias.get((kind, node.name))
            if target and target != oname and claim(oname, "alias"):
                f.body.append(((relp, line), f"{oname} :: {target}\n"))
            return
        if not claim(oname, "struct"):
            return
        txt = comment_block(doc)
        if d is None:
            txt += f"{oname} :: struct {{}} // opaque\n"
        else:
            emitted_tags.add(id(d))
            drel = rel_header(d.coord.file)
            txt += f"{oname} :: {struct_body(d, cname, 0, drel)}\n"
            sz = GCCV.sizes.get(cname)
            if sz is None and d.name:
                sz = GCCV.sizes.get(("struct " if isinstance(d, c_ast.Struct) else "union ") + d.name)
            if sz is not None:
                txt += f"#assert(size_of({oname}) == 0x{sz:X})\n"
        f.body.append(((relp, line), txt))

    # ---- walk items in header order
    for relp, line, kind, node in sorted(M.items, key=lambda x: (x[0], x[1])):
        f = fo(relp)
        if kind == "typedef":
            t = node.type
            inner = t
            while isinstance(inner, c_ast.TypeDecl):
                inner = inner.type
            startline = inner.coord.line if isinstance(inner, (c_ast.Struct, c_ast.Union, c_ast.Enum)) and inner.coord else line
            doc = doc_before(relp, startline)
            if isinstance(inner, (c_ast.Struct, c_ast.Union)):
                emit_struct(f, relp, startline, node.name, inner, doc)
            elif isinstance(inner, c_ast.Enum):
                d = tag_def(inner)
                if d is None:
                    if claim(strip_type(node.name), "enum-alias"):
                        f.body.append(((relp, line), f"{strip_type(node.name)} :: i32\n"))
                else:
                    emit_enum(f, relp, startline, node.name, d, doc)
            else:
                oname = strip_type(node.name)
                if PRIM_TYPEDEF.match(node.name):
                    continue
                try:
                    if isinstance(t, c_ast.FuncDecl):
                        target = "#type " + proc_type(t)
                    elif isinstance(t, c_ast.PtrDecl) and isinstance(t.type, c_ast.FuncDecl):
                        target = "#type " + proc_type(t.type)
                    else:
                        target = otype(t)
                except ValueError as e:
                    report["notes"].append(f"typedef {node.name}: {e}")
                    continue
                if target == oname:
                    continue
                if target == "void":
                    target = "struct {} // opaque (typedef void)"
                if claim(oname, "typedef"):
                    c = trailing_comment(relp, line)
                    f.body.append(((relp, line), comment_block(doc) + f"{oname} :: {target}" + (f" // {c}" if c else "") + "\n"))
        elif kind == "tagdef":
            doc = doc_before(relp, line)
            if isinstance(node, c_ast.Enum):
                emit_enum(f, relp, line, node.name, node, doc)
            else:
                emit_struct(f, relp, line, node.name, node, doc)
        elif kind == "func":
            name = node.name
            fd = node.type
            quals = (node.funcspec or []) + (node.storage or [])
            lib = stubs.get(name)
            if lib is None:
                report["no_stub"].append((name, relp))
                continue
            try:
                ps, variadic = params_of(fd)
                float_ps = [is_float_by_value(t) for _, t in ps]
                ret_float = is_float_by_value(fd.type)
                hfa = any(struct_has_float(t) and isinstance(resolve(t), (c_ast.Struct, c_ast.Union)) for _, t in ps) \
                    or isinstance(resolve(fd.type), (c_ast.Struct, c_ast.Union))
                if hfa:
                    report["float_struct"].append((name, relp))
                    continue
                noret = "SCE_NORETURN" in "\n".join(hdr_lines(relp)[max(0, line - 2):line])
                doc = doc_before(relp, line)
                if any(float_ps) or ret_float:
                    # float bridge
                    cparams, cargs, oparts = [], [], []
                    for (pn, pt), isf in zip(ps, float_ps):
                        if isf:
                            is_d = base_names(resolve(pt)) != "float"
                            cparams.append(("uint64_t " if is_d else "uint32_t ") + pn)
                            cargs.append(("u2d(%s)" if is_d else "u2f(%s)") % pn)
                        else:
                            cparams.append(c_decl(pt, pn))
                            cargs.append(pn)
                        oparts.append(f"{ident(pn)}: {otype(pt, in_param=True)}")
                    call = f"{name}({', '.join(cargs)})"
                    if ret_float:
                        is_d = base_names(resolve(fd.type)) != "float"
                        rett = "uint64_t" if is_d else "uint32_t"
                        body = f"return {'d2u' if is_d else 'f2u'}({call});"
                    elif is_void(fd.type):
                        rett, body = "void", call + ";"
                    else:
                        rett, body = c_decl(fd.type, "").strip(), f"return {call};"
                    bridge_c.append((relp, f"{rett} vito_{name}({', '.join(cparams) or 'void'}) {{ {body} }}\n"))
                    sig = "proc(" + ", ".join(oparts) + ")"
                    if not is_void(fd.type):
                        sig += " -> " + otype(fd.type)
                    text = comment_block(doc, "    ") + f'    @(link_name = "vito_{name}") {name} :: {sig} ---\n'
                    f.funcs.setdefault("sce_bridge", []).append(text)
                    report["bridged"].append((name, relp, lib))
                    f.bridge_libs = getattr(f, "bridge_libs", set()) | {lib}
                else:
                    sig = proc_sig(fd, noreturn=noret)
                    text = comment_block(doc, "    ") + f"    {name} :: {sig} ---\n"
                    f.funcs.setdefault(lib, []).append(text)
                f.nfuncs += 1
            except (ValueError, KeyError) as e:
                report["notes"].append(f"function {name} ({relp}): {e}")

    # ---- macros
    for name, (val, relp, line) in macro_def.items():
        k = macro_kind.get(name)
        if name.startswith("_") or name.endswith("_H_") or name.endswith("_H"):
            continue
        if name in ("SCE_ALIGN", "SCE_DEPRECATED", "SCE_NORETURN", "SCE_CONSTRUCTOR", "SCE_DESTRUCTOR") or name.startswith("VITASDK_BUILD"):
            continue
        f = fo(relp)
        c = trailing_comment(relp, line)
        tail = f" // {c}\n" if c else "\n"
        if k == "int":
            oname = strip_const(name)
            v = GCCV.consts[name]
            if not claim(oname, "macro"):
                if oname in enum_const_emitted or emitted_names.get(oname) == "macro":
                    continue
                report["macros_skipped"].append((name, f"name {oname} already used by a {emitted_names[oname]}"))
                continue
            like_hex = "0x" in val.lower() or "<<" in val or (v >= 256 and re.search(r"[A-Za-z_]", val) is not None)
            if "ERROR" in name and 0x80000000 <= v < 0x90000000:
                vtxt = errval(v)
            elif re.fullmatch(r"\(?0[0-7]+\)?", val):
                vtxt = "0o%o" % v
            else:
                vtxt = hexish(v, like_hex)
            f.body.append(((relp, line), f"{oname} :: {vtxt}{tail}"))
        elif k == "string":
            oname = strip_const(name)
            if claim(oname, "macro"):
                f.body.append(((relp, line), f"{oname} :: {val}{tail}"))
        elif k == "float":
            oname = strip_const(name)
            num = val.strip("() ").rstrip("fF")
            if claim(oname, "macro"):
                f.body.append(((relp, line), f"{oname} :: {num}{tail}"))
        elif k == "typealias":
            oname = strip_type(name)
            try:
                target = odin_named(val)
            except ValueError:
                continue
            if target != oname and target != "void" and claim(oname, "macro"):
                f.body.append(((relp, line), f"{oname} :: {target}{tail}"))
        elif k == "funcalias":
            if val in stubs and claim(name, "macro"):
                f.body.append(((relp, line), f"{name} :: {val}{tail}"))
        else:
            report["macros_skipped"].append((name, val[:70]))

    for name, relp, line in M.inline_funcs:
        report["inline"].append((name, relp))

    # ---- opaque types that were only ever forward-declared
    opaque_txt = ""
    for o in sorted(PENDING_OPAQUE):
        if claim(o, "opaque"):
            opaque_txt += f"{o} :: struct {{}}\n"

    # ---- write files
    os.makedirs(OUT, exist_ok=True)
    for p in glob.glob(os.path.join(OUT, "*.odin")):
        if open(p, encoding="utf-8").readline().startswith(MARK):
            os.remove(p)
    total_funcs = 0
    index = []
    for key in sorted(files):
        f = files[key]
        if not f.body and not f.funcs:
            continue
        libs = sorted(l for l in f.funcs if l != "sce_bridge")
        txt = MARK + " from " + ", ".join(f.headers) + ". Do not edit.\n"
        txt += "package sce\n\n"
        link = ["-l" + l for l in libs]
        if "sce_bridge" in f.funcs:
            link += ["-l" + l for l in sorted(getattr(f, "bridge_libs", set())) if "-l" + l not in link]
            link.append("lib/sce/bridge.c (add `sce` to BRIDGES in build.bat)")
        if link:
            txt += "// Link: " + " ".join(link) + "\n\n"
        for l in libs:
            txt += f'foreign import {imp_name(l)} "system:{l}"\n'
        if "sce_bridge" in f.funcs:
            txt += 'foreign import sce_bridge "system:sce_bridge"\n'
        if f.funcs:
            txt += "\n"
        f.body.sort(key=lambda b: (0 if b[0][0].startswith("psp2common/") else 1, b[0][0], b[0][1]))
        prev_simple = False
        for _, b in f.body:
            simple = b.count("\n") == 1 and not b.startswith("//")
            if not (simple and prev_simple):
                txt += "\n" if not txt.endswith("\n\n") else ""
            txt += b
            prev_simple = simple
        for l in libs + (["sce_bridge"] if "sce_bridge" in f.funcs else []):
            txt += f'\n@(default_calling_convention = "c")\nforeign {imp_name(l) if l != "sce_bridge" else l} {{\n'
            txt += "\n".join(f.funcs[l]) if any(t.lstrip().startswith("//") for t in f.funcs[l]) else "".join(f.funcs[l])
            txt += "}\n"
        open(os.path.join(OUT, key + ".odin"), "w", encoding="utf-8", newline="\n").write(txt)
        total_funcs += f.nfuncs
        index.append((key, f.headers, f.nfuncs, libs))
    if opaque_txt:
        open(os.path.join(OUT, "opaque.odin"), "w", encoding="utf-8", newline="\n").write(
            MARK + ". Do not edit.\npackage sce\n\n// Types the headers only forward-declare.\n" + opaque_txt)

    # ---- bridge.c
    btxt = ("// GENERATED by tools/bindgen/gen.py. Do not edit.\n//\n"
            "// Float ABI bridge for the SCE functions that take or return float/double by\n"
            "// value. Odin passes them in integer registers; the SDK expects VFP registers.\n\n"
            "#include <stdint.h>\n#include <string.h>\n")
    for h in sorted(set(r for r, _ in bridge_c)):
        btxt += f"#include <{h}>\n"
    btxt += ('#include "../bridge_utils.h"\n\n'
             "static inline double   u2d(uint64_t v) { double   d; memcpy(&d, &v, sizeof d); return d; }\n"
             "static inline uint64_t d2u(double   d) { uint64_t v; memcpy(&v, &d, sizeof v); return v; }\n\n")
    last = None
    for r, t in bridge_c:
        if r != last:
            btxt += f"\n// {r}\n"
            last = r
        btxt += t
    open(os.path.join(OUT, "bridge.c"), "w", encoding="utf-8", newline="\n").write(btxt)

    # ---- layout verification file (checked with `odin check`, then deleted by verify.py)
    v = MARK + ". Temporary layout check.\npackage sce\n\n"
    for (tn, fn), off in GCCV.offsets.items():
        on = strip_type(tn)
        if emitted_names.get(on) == "struct":
            v += f"#assert(offset_of({on}, {ident(fn)}) == {off})\n"
    open(os.path.join(WORK, "layout_check.odin"), "w", encoding="utf-8", newline="\n").write(v)

    write_report(index, total_funcs)
    print(f"{len(index)} files, {total_funcs} functions, {len(report['bridged'])} bridged, "
          f"{len(report['no_stub'])} without a stub, {len(report['inline'])} inline, "
          f"{len(report['macros_skipped'])} macros skipped, {len(report['notes'])} notes")


def imp_name(lib):
    s = re.sub(r"_stub$", "", lib)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).lower()
    return "lib_" + s


def c_decl(t, name):
    """Minimal C spelling of a parameter type for bridge.c (by-value scalars and pointers)."""
    from pycparser import c_generator
    g = c_generator.CGenerator()
    s = g.visit(c_ast.Typename(name=None, quals=[], align=None, type=strip_declname(t)))
    if "(*" in s or "[" in s:
        # function pointers / arrays: splice the name in
        if "(*)" in s:
            return s.replace("(*)", f"(*{name})", 1)
        if "[" in s:
            i = s.index("[")
            return s[:i] + " " + name + s[i:]
    return (s + " " + name).strip()


def strip_declname(t):
    import copy
    t = copy.deepcopy(t)
    n = t
    while n is not None:
        if isinstance(n, c_ast.TypeDecl):
            n.declname = None
            break
        n = getattr(n, "type", None)
    return t


def write_report(index, total_funcs):
    L = ["# Binding generator report", "",
         "Written by `tools/bindgen/gen.py`. It lists what was generated and, more importantly,",
         "what was **not** bound and why.", "",
         f"- Files: {len(index)}", f"- Functions bound: {total_funcs}",
         f"- Through the float bridge (`lib/sce/bridge.c`): {len(report['bridged'])}", ""]
    L += ["## Generated files", "", "| File | Headers | Functions | Stub libraries |", "|---|---|---|---|"]
    for key, hs, n, libs in index:
        L.append(f"| `{key}.odin` | {', '.join(hs)} | {n} | {' '.join('-l' + l for l in libs)} |")
    L += ["", "## Float-bridged functions", ""]
    for n, r, lib in report["bridged"]:
        L.append(f"- `{n}` ({r}, {lib})")
    L += ["", "## Headers skipped", ""]
    for r, why in report["skipped_headers"]:
        L.append(f"- `{r}`: {why}")
    L += ["", "## Functions declared in a header but exported by no user-mode stub library (not bound)", ""]
    for n, r in report["no_stub"]:
        L.append(f"- `{n}` ({r})")
    L += ["", "## Functions that pass or return a struct by value (not bound; need a hand-written bridge)", ""]
    for n, r in report["float_struct"]:
        L.append(f"- `{n}` ({r})")
    L += ["", "## `static inline` functions in headers (no symbol to bind; ported by hand in lib/sce/inline.odin)", ""]
    for n, r in report["inline"]:
        L.append(f"- `{n}` ({r})")
    L += ["", "## Function-like macros (the useful ones are ported by hand in lib/sce/inline.odin)", ""]
    for n, r in report["func_macros"]:
        if is_sdk(r) and not n.startswith("_") and not n.startswith("VITASDK"):
            L.append(f"- `{n}` ({r})")
    L += ["", "## Object-like macros that were not translated", ""]
    for n, why in report["macros_skipped"]:
        if not n.startswith("_"):
            L.append(f"- `{n}`: `{why}`")
    L += ["", "## Notes", ""]
    for n in report["notes"]:
        L.append(f"- {n}")
    open(os.path.join(HERE, "report.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")


